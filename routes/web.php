Route::middleware('auth')->group(function () {

    Route::view('/account/suspended', 'auth.suspended')->name('account.suspended');

    // Generic dashboard — redirects to the correct role-specific dashboard.
    Route::get('/dashboard', function () {
        $user = auth()->user();

        return match (true) {
            $user->isCandidate() => redirect()->route('candidate.dashboard'),
            $user->isEmployer() => redirect()->route('employer.dashboard'),
            $user->isAdmin() => redirect()->route('admin.dashboard'),
            $user->isOwner() => redirect()->route('admin.dashboard'),
            default => redirect()->route('home'),
        };
    })->name('dashboard');

    // Profile (any authenticated user)
    Route::get('/profile', [ProfileController::class, 'edit'])->name('profile.edit');
    Route::patch('/profile', [ProfileController::class, 'update'])->name('profile.update');
    Route::delete('/profile', [ProfileController::class, 'destroy'])->name('profile.destroy');
});

